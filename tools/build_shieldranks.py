"""Builds the ItemsAdder content pack `shieldranks` from the "ANIMATED 9+ Shield rank icons" pack.

Usage: python -I build_shieldranks.py <icon pack folder> <output folder>

<icon pack folder> is the folder holding 32x32_Versions/ and Animated_Versions/.
<output folder> becomes the ItemsAdder content folder (copy it to plugins/ItemsAdder/contents/shieldranks/).

For every icon it writes:
  textures/font/<id>/<n>.png      one frame of the 32x32 GIF, fully composited (font image <id>_<n>)
  textures/font/<id>_static.png   the static 32x32 PNG (font image <id>_static, for chat)
  textures/item/<id>.png(.mcmeta) a vertical strip of the frames, animated by the client (item <id>_item)
and configs/icons.yml declaring all of them. Prints the frame count of each icon (BoxClans icons.yml `frames`).
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageSequence

NAMESPACE = "shieldranks"
SCALE_RATIO = 9
Y_POSITION = 8


def icon_id(name):
    """Dragon_Animated_32x32.gif / Blank_Gold__Animated_32x32.gif / Dragon_32x33.png -> dragon / blank_gold."""
    stem = Path(name).stem
    stem = re.sub(r"_+Animated", "", stem)
    stem = re.sub(r"_\d+x\d+$", "", stem)
    return stem.lower()


def frames_of(gif):
    with Image.open(gif) as im:
        out, durations = [], set()
        for frame in ImageSequence.Iterator(im):
            durations.add(frame.info.get("duration", 100))
            out.append(frame.convert("RGBA").copy())
        return out, durations


def main(src, dst):
    src, dst = Path(src), Path(dst)
    textures = dst / "resourcepack" / "assets" / NAMESPACE / "textures"
    statics = {icon_id(p.name): p for p in (src / "32x32_Versions").glob("*.png")}
    gifs = sorted((src / "Animated_Versions" / "32x32_Animated_Version").glob("*.gif"))
    if not gifs:
        sys.exit("no GIF found in " + str(src / "Animated_Versions" / "32x32_Animated_Version"))

    fonts, items, counts = [], [], {}
    for gif in gifs:
        iid = icon_id(gif.name)
        frames, durations = frames_of(gif)
        counts[iid] = (len(frames), sorted(durations))
        font_dir = textures / "font" / iid
        font_dir.mkdir(parents=True, exist_ok=True)
        for n, frame in enumerate(frames, 1):
            frame.save(font_dir / f"{n}.png")
            fonts.append((f"{iid}_{n}", f"font/{iid}/{n}.png"))

        static = statics.get(iid)
        if static is None:
            sys.exit("no static PNG for " + iid)
        with Image.open(static) as im:
            im.convert("RGBA").save(textures / "font" / f"{iid}_static.png")
        fonts.append((f"{iid}_static", f"font/{iid}_static.png"))

        item_dir = textures / "item"
        item_dir.mkdir(parents=True, exist_ok=True)
        w, h = frames[0].size
        strip = Image.new("RGBA", (w, h * len(frames)))
        for n, frame in enumerate(frames):
            strip.paste(frame, (0, h * n))
        strip.save(item_dir / f"{iid}.png")
        ticks = max(1, round(max(durations) / 50))
        (item_dir / f"{iid}.png.mcmeta").write_text(
            '{\n  "animation": {\n    "frametime": %d\n  }\n}\n' % ticks, encoding="utf-8")
        items.append(iid)

    lines = [
        "# Generated by BoxClans/tools/build_shieldranks.py: animated clan shield icons for BoxClans (icons.yml).",
        "# Font images <id>_<n> are the GIF frames, <id>_static is the chat icon, <id>_item the shop item.",
        "info:",
        f"  namespace: {NAMESPACE}",
        "",
        "font_images:",
    ]
    for name, path in fonts:
        lines += [
            f"  {name}:",
            f'    path: "{path}"',
            f"    scale_ratio: {SCALE_RATIO}",
            f"    y_position: {Y_POSITION}",
            "    suggest_in_command: false",
            "    show_in_gui: false",
        ]
    lines += ["", "items:"]
    for iid in items:
        lines += [
            f"  {iid}_item:",
            f"    display_name: {iid}",
            "    resource:",
            "      material: PAPER",
            "      generate: true",
            "      textures:",
            f"        - item/{iid}.png",
        ]
    (dst / "configs").mkdir(parents=True, exist_ok=True)
    (dst / "configs" / "icons.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    for iid, (n, d) in counts.items():
        print(f"{iid}: {n} frames, duration {d} ms")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
